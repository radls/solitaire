import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dailyFreeCellDeal, dailySeed } from "../src/daily.js";
import { deal as dealFreeCell, listLegalMoves as listFreeCell } from "../src/game/freecell.js";
import { deal as dealGolf, listLegalMoves as listGolf } from "../src/game/golf.js";
import { deal as dealKings, listLegalMoves as listKings } from "../src/game/kings.js";
import { deal as dealKlondike, isStuck, listLegalMoves as listKlondike } from "../src/game/klondike.js";

const START = "2026-10-13";
const DAYS = 70;
const GAMES = ["klondike", "freecell", "golf", "kings"];
const MINUTES = [10, 11, 12, 13, 14, 15];
const GOLF_LEFT = [5, 6, 7, 8];
const MAX_STEPS = 400;

export function isOpeningPlayable(game, seed) {
  if (game === "klondike") {
    const state = dealKlondike({ seed, drawCount: 1 });
    return listKlondike(state).length > 0 && !isStuck(state);
  }
  if (game === "freecell") {
    const state = dealFreeCell(seed);
    return listFreeCell(state).length > 0;
  }
  if (game === "golf") {
    const state = dealGolf({ seed });
    return listGolf(state).length > 0;
  }
  if (game === "kings") {
    const state = dealKings({ seed });
    return listKings(state).length > 0 && state.stuck !== true;
  }
  return false;
}

function openingSeed(game, date) {
  if (game === "freecell") return dailyFreeCellDeal(date);
  return dailySeed(game, date);
}

function nextCandidate(game, seed) {
  if (game === "freecell") {
    const n = Number(seed);
    return n >= 32000 ? 1 : n + 1;
  }
  return (Number(seed) + 1) >>> 0;
}

export function goalFor(game, occurrence) {
  const slot = occurrence % 3;
  if (game === "golf") {
    if (slot === 0) return { type: "golfUnder", n: GOLF_LEFT[occurrence % GOLF_LEFT.length] };
    if (slot === 1) return { type: "maxMinutes", n: MINUTES[occurrence % MINUTES.length] };
    return { type: "noUndo" };
  }
  if (slot === 0) return { type: "noUndo" };
  if (slot === 1) return { type: "maxMoves", n: game === "klondike" ? 160 : 120 };
  return { type: "maxMinutes", n: MINUTES[occurrence % MINUTES.length] };
}

export function goalText(goal) {
  if (goal.type === "noUndo") return "Win with no Undo";
  if (goal.type === "maxMoves") return `Win in under ${goal.n} moves`;
  if (goal.type === "maxMinutes") return `Win in under ${goal.n} minutes`;
  if (goal.type === "golfUnder") return `Golf: finish with under ${goal.n} cards left`;
  return "";
}

function addDays(key, n) {
  const [y, m, d] = key.split("-").map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d + n));
  const yy = dt.getUTCFullYear();
  const mm = String(dt.getUTCMonth() + 1).padStart(2, "0");
  const dd = String(dt.getUTCDate()).padStart(2, "0");
  return `${yy}-${mm}-${dd}`;
}

function playableSeed(game, date) {
  let seed = openingSeed(game, date);
  for (let step = 0; step < MAX_STEPS; step++) {
    if (isOpeningPlayable(game, seed)) return { seed, steps: step };
    seed = nextCandidate(game, seed);
  }
  throw new Error(`No playable ${game} seed for ${date}`);
}

export function buildPicks() {
  const seen = { klondike: 0, freecell: 0, golf: 0, kings: 0 };
  const picks = [];
  for (let i = 0; i < DAYS; i++) {
    const date = addDays(START, i);
    const game = GAMES[i % GAMES.length];
    const { seed, steps } = playableSeed(game, date);
    const goal = goalFor(game, seen[game]);
    seen[game] += 1;
    const text = goalText(goal);
    if (!text) throw new Error(`Empty goal text for ${date}`);
    picks.push({ date, game, seed, goal, text, steps });
  }
  return picks;
}

function formatGoal(goal) {
  if (goal.n == null) return `{ type: "${goal.type}" }`;
  return `{ type: "${goal.type}", n: ${goal.n} }`;
}

function formatFile(picks) {
  const rows = picks.map(
    (entry) =>
      `  { date: "${entry.date}", game: "${entry.game}", seed: ${entry.seed}, goal: ${formatGoal(entry.goal)}, text: "${entry.text}" },`,
  );
  return `// Generated by scripts/gen-groks-pick.mjs — run \`npm run gen:pick\` to rebuild.\nexport const GROKS_PICK = [\n${rows.join("\n")}\n];\n`;
}

function writePicks() {
  const picks = buildPicks();
  const out = join(dirname(fileURLToPath(import.meta.url)), "../src/groks-pick-data.js");
  writeFileSync(out, formatFile(picks));
  const stepped = picks.filter((entry) => entry.steps > 0).length;
  console.log(`Wrote ${picks.length} picks to ${out} (${stepped} stepped past the daily seed).`);
}

const invoked = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invoked) writePicks();
